/**
 * Reads divisionGapFill.ts entities (which use plain strings)
 * and regenerates with proper Entity-compatible types.
 */
import { divisionGapFillEntities } from '../src/data/catalog/divisionGapFill'
import * as fs from 'fs'
import * as path from 'path'

// Transform entities to proper types
const fixed = divisionGapFillEntities.map((raw: any) => {
  const e: any = { ...raw }
  // Fix causes: string[] → EntityCause[]
  if (Array.isArray(e.causes)) {
    e.causes = e.causes.map((c: any) =>
      typeof c === 'string' ? { title: c, type: 'Context', year: '' } : c
    )
  }
  // Fix effects: string[] → EntityEffect[]
  if (Array.isArray(e.effects)) {
    e.effects = e.effects.map((ef: any) =>
      typeof ef === 'string' ? { title: ef, type: 'Outcome', year: '' } : ef
    )
  }
  // Fix relationships: {type,target}[] → EntityRelationship[]
  if (Array.isArray(e.relationships)) {
    e.relationships = e.relationships.map((r: any) => {
      if (r.sourceSlug) return r // already correct
      return {
        sourceSlug: e.slug,
        sourceName: e.name,
        verb: r.type || 'OCCURS_IN',
        targetSlug: r.target || '',
        targetName: r.target || '',
      }
    })
  }
  // Fix places: string[] → EntityPlace[]
  if (Array.isArray(e.places)) {
    e.places = e.places.map((p: any) =>
      typeof p === 'string' ? { name: p, role: 'Location' } : p
    )
  }
  // Fix texts: ensure array
  if (!Array.isArray(e.texts)) e.texts = []

  // Derive eraSlug from era
  if (!e.eraSlug) {
    const eraMap: Record<string, string> = {
      'Prehistoric': 'prehistoric',
      'Classical': 'classical',
      'Classical/Ancient': 'classical',
      'Medieval': 'medieval',
      'Early Modern': 'early-modern',
      'Modern': 'modern',
      'Contemporary': 'contemporary',
    }
    e.eraSlug = eraMap[e.era] || e.era?.toLowerCase().replace(/\s+/g, '-') || 'classical'
  }

  // Derive region from first place or default
  if (!e.region) {
    e.region = (e.places && e.places.length > 0)
      ? (typeof e.places[0] === 'string' ? e.places[0] : e.places[0].name)
      : 'Global'
  }

  // Derive continent from region or default
  if (!e.continent) e.continent = 'Global'

  // Always set status
  if (!e.status) e.status = 'Published'

  return e
})

// Generate TypeScript output
const lines: string[] = []
lines.push(`/**`)
lines.push(` * Division Gap Fill — ${fixed.length} entities covering all previously empty divisions.`)
lines.push(` * Auto-generated by scripts/fix-gap-types.ts — uses proper Entity-compatible types.`)
lines.push(` */`)
lines.push(`import type { Entity } from '../entityTypes'`)
lines.push(``)
lines.push(`export const divisionGapFillEntities: Entity[] = [`)

for (const e of fixed) {
  lines.push(`  {`)
  lines.push(`    slug: ${JSON.stringify(e.slug)},`)
  lines.push(`    name: ${JSON.stringify(e.name)},`)
  lines.push(`    label: ${JSON.stringify(e.label)},`)
  lines.push(`    callNumber: ${JSON.stringify(e.callNumber)},`)
  lines.push(`    era: ${JSON.stringify(e.era)},`)
  lines.push(`    eraSlug: ${JSON.stringify(e.eraSlug)},`)
  lines.push(`    region: ${JSON.stringify(e.region)},`)
  lines.push(`    continent: ${JSON.stringify(e.continent)},`)
  lines.push(`    status: ${JSON.stringify(e.status)},`)
  lines.push(`    summary: ${JSON.stringify(e.summary)},`)
  lines.push(`    causes: ${JSON.stringify(e.causes)},`)
  lines.push(`    effects: ${JSON.stringify(e.effects)},`)
  lines.push(`    relationships: ${JSON.stringify(e.relationships)},`)
  lines.push(`    subjects: ${JSON.stringify(e.subjects)},`)
  lines.push(`    subjectHeadings: ${JSON.stringify(e.subjectHeadings)},`)
  lines.push(`    frameworks: ${JSON.stringify(e.frameworks)},`)
  lines.push(`    places: ${JSON.stringify(e.places)},`)
  lines.push(`    texts: ${JSON.stringify(e.texts)},`)
  lines.push(`  },`)
}

lines.push(`]`)

const outPath = path.resolve(__dirname, '../src/data/catalog/divisionGapFill.ts')
fs.writeFileSync(outPath, lines.join('\n') + '\n', 'utf8')
console.log(`Wrote ${fixed.length} entities to ${outPath}`)
