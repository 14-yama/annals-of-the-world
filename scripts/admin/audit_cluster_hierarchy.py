#!/usr/bin/env python3
"""Audit cluster hierarchy: report parents, children, roots, and cycles.

Writes `data/Relationships/cluster_hierarchy_audit.md` and prints a summary.
No files are modified.
"""

import json
from pathlib import Path
from collections import defaultdict, deque

ROOT = Path(__file__).resolve().parents[2]
CLUSTERS_DIR = ROOT / "docs" / "clusters"
REL_DIR = ROOT / "data" / "Relationships"
OUT = REL_DIR / "cluster_hierarchy_audit.md"


def load_clusters():
    names = []
    if CLUSTERS_DIR.exists():
        for p in CLUSTERS_DIR.iterdir():
            if p.is_dir():
                names.append(p.name)
    return set(names)


def load_relationships():
    rels = []
    for p in sorted(REL_DIR.iterdir()):
        if p.suffix != '.json':
            continue
        if 'bak.' in p.name:
            continue
        try:
            data = json.loads(p.read_text(encoding='utf-8'))
        except Exception:
            continue
        for r in data.get('relationships', []):
            rels.append((p.name, r))
    return rels


def load_nodes():
    nodes = {}  # cluster -> set(slugs)
    for p in sorted((ROOT / 'data' / 'Nodes').iterdir()):
        if p.suffix != '.json':
            continue
        if 'bak.' in p.name:
            continue
        try:
            data = json.loads(p.read_text(encoding='utf-8'))
        except Exception:
            continue
        cluster = data.get('_meta', {}).get('cluster')
        slugs = set()
        for n in data.get('nodes', []):
            slug = n.get('slug')
            if slug:
                slugs.add(slug)
        if cluster:
            nodes[cluster] = slugs
    return nodes


def build_graph(clusters, rels):
    parents = defaultdict(list)  # child -> [parents]
    children = defaultdict(list)  # parent -> [children]
    rel_index = defaultdict(list)  # cluster -> [ (file,rel) ]

    for fname, r in rels:
        t = r.get('type')
        s = r.get('start_slug')
        e = r.get('end_slug')
        rel_index[s].append((fname, r))
        rel_index[e].append((fname, r))
        # consider only inter-cluster part/whole relationships
        if s in clusters and e in clusters and t == 'IS_PART_OF':
            parents[s].append((e, fname))
            children[e].append((s, fname))
    return parents, children, rel_index


def find_roots(clusters, parents):
    roots = []
    for c in sorted(clusters):
        if not parents.get(c):
            roots.append(c)
    return roots


def detect_cycles(clusters, parents):
    # detect cycles in parent pointers using DFS
    visited = set()
    stack = set()
    cycles = []

    def dfs(node, path):
        if node in stack:
            # cycle detected
            idx = path.index(node)
            cycles.append(path[idx:])
            return
        if node in visited:
            return
        visited.add(node)
        stack.add(node)
        for p, _ in parents.get(node, []):
            dfs(p, path + [p])
        stack.remove(node)

    for c in sorted(clusters):
        dfs(c, [c])
    return cycles


def compute_depths(roots, parents, clusters):
    # BFS from roots downward through children (we need reverse mapping)
    depths = {c: None for c in clusters}
    q = deque()
    for r in roots:
        depths[r] = 0
        q.append(r)
    # build reverse parents -> children mapping
    reverse = defaultdict(list)
    for child, ps in parents.items():
        for p, _ in ps:
            reverse[p].append(child)
    while q:
        node = q.popleft()
        for ch in reverse.get(node, []):
            if depths[ch] is None or depths[ch] > depths[node] + 1:
                depths[ch] = depths[node] + 1
                q.append(ch)
    return depths


def write_report(clusters, parents, children, rel_index, roots, cycles, depths):
    lines = []
    lines.append('# Cluster hierarchy audit\n')
    lines.append('Generated by `scripts/admin/audit_cluster_hierarchy.py`\n')
    lines.append('')
    lines.append('## Summary')
    lines.append(f'- clusters found: {len(clusters)}')
    lines.append(f'- roots (no IS_PART_OF parent): {len(roots)}')
    lines.append(f'- clusters with multiple parents: {sum(1 for c in clusters if len(parents.get(c,[]))>1)}')
    lines.append(f'- cycles detected: {len(cycles)}')
    lines.append('')

    lines.append('## Roots')
    for r in roots:
        lines.append(f'- {r} (depth 0)')
    lines.append('')

    lines.append('## Per-cluster details')
    lines.append('| cluster | parents | parent_files | children_count | depth | note |')
    lines.append('|---|---|---|---:|---:|---|')
    # augment with node coverage checks
    nodes_map = load_nodes()
    # build map of relationships by cluster file
    rels_by_file = defaultdict(list)
    for fname, r in rel_index.items():
        # rel_index maps slug -> list of (file, rel), but we want file -> rels
        pass
    # build file-level relationships
    file_rels = defaultdict(list)
    for fname, r in load_relationships():
        file_rels[fname].append(r)

    for c in sorted(clusters):
        ps = parents.get(c, [])
        parent_names = ', '.join(p for p,_ in ps) if ps else ''
        parent_files = ', '.join(f for _,f in ps) if ps else ''
        child_count = len(children.get(c, []))
        d = depths.get(c)
        note = ''
        if len(ps) > 1:
            note = 'multiple parents'
        elif len(ps) == 0:
            note = 'root'
        # node coverage
        node_slugs = nodes_map.get(c, set())
        # collect slugs referenced in relationships for this cluster file
        rel_file = f'relationships.{c}.json'
        referenced = set()
        missing_refs = set()
        for r in file_rels.get(rel_file, []):
            s = r.get('start_slug')
            e = r.get('end_slug')
            if s:
                referenced.add(s)
                if not any(s in sset for sset in nodes_map.values()):
                    missing_refs.add(s)
            if e:
                referenced.add(e)
                if not any(e in sset for sset in nodes_map.values()):
                    missing_refs.add(e)
        nodes_without_edges = sorted(node_slugs - referenced)
        note_extra = ''
        if nodes_without_edges:
            note_extra = f' nodes_without_edges={len(nodes_without_edges)}'
        if missing_refs:
            note_extra += f' missing_node_refs={len(missing_refs)}'
        combined_note = (note + note_extra).strip()
        lines.append(f'| {c} | {parent_names} | {parent_files} | {child_count} | {d if d is not None else "?"} | {combined_note} |')

    # Add detailed per-cluster node reports
    lines.append('')
    lines.append('## Per-cluster node coverage')
    for c in sorted(clusters):
        node_slugs = nodes_map.get(c, set())
        rel_file = f'relationships.{c}.json'
        referenced = set()
        missing_refs = set()
        for r in file_rels.get(rel_file, []):
            s = r.get('start_slug')
            e = r.get('end_slug')
            if s:
                referenced.add(s)
                if not any(s in sset for sset in nodes_map.values()):
                    missing_refs.add((s, 'start', r.get('_key')))
            if e:
                referenced.add(e)
                if not any(e in sset for sset in nodes_map.values()):
                    missing_refs.add((e, 'end', r.get('_key')))
        nodes_without_edges = sorted(node_slugs - referenced)
        lines.append(f'### {c}')
        lines.append(f'- total nodes: {len(node_slugs)}')
        lines.append(f'- nodes without relationships in {rel_file}: {len(nodes_without_edges)}')
        if nodes_without_edges:
            for n in nodes_without_edges[:50]:
                lines.append(f'  - {n}')
        lines.append(f'- missing node references in relationships: {len(missing_refs)}')
        if missing_refs:
            for m in list(missing_refs)[:50]:
                lines.append(f'  - {m[0]} ({m[1]}) referenced in rel _key={m[2]}')
        lines.append('')

    lines.append('\n')
    lines.append('## Cycles')
    if not cycles:
        lines.append('No cycles detected.')
    else:
        for cyc in cycles:
            lines.append('- ' + ' -> '.join(cyc))
    lines.append('\n')

    lines.append('## Suspicious relationships (non-cluster parents referenced)')
    suspicious = []
    for c in sorted(clusters):
        for p, fname in parents.get(c, []):
            if p not in clusters:
                suspicious.append((c,p,fname))
    if not suspicious:
        lines.append('None found.')
    else:
        for c,p,f in suspicious:
            lines.append(f'- {c} has parent {p} referenced in {f} (parent not a cluster directory)')

    OUT.write_text('\n'.join(lines), encoding='utf-8')
    return OUT


def main():
    clusters = load_clusters()
    rels = load_relationships()
    parents, children, rel_index = build_graph(clusters, rels)
    roots = find_roots(clusters, parents)
    cycles = detect_cycles(clusters, parents)
    depths = compute_depths(roots, parents, clusters)
    out = write_report(clusters, parents, children, rel_index, roots, cycles, depths)
    print('Audit written to', out)
    # print quick summary to stdout
    print('clusters:', len(clusters))
    print('roots (no parent):', len(roots))
    print('clusters with multiple parents:', sum(1 for c in clusters if len(parents.get(c,[]))>1))
    print('cycles detected:', len(cycles))

if __name__ == '__main__':
    raise SystemExit(main())
