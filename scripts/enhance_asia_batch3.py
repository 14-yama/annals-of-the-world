    total = 0
    for slug in sorted(DATA):
        n = patch_country(slug, copy.deepcopy(DATA[slug]))
        print(f"  OK  {slug}: {n} new sections + expanded fields added")
        total += 1
    print(f"\nBatch 3 done. {total} countries enhanced.")


