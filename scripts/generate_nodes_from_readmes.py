#!/usr/bin/env python3
"""Generate `data/Nodes/nodes.<cluster>.json` from cluster READMEs.

This is a clearer, repository-level name replacing the older
`populate_nodes_from_readme_early_christianity.py` script. It scans all
`docs/clusters/*/README.md` files, extracts node tables, and writes
registry-compliant JSON per cluster.
"""
import re
import json
from pathlib import Path
import shutil
from datetime import datetime, timezone

ROOT = Path(__file__).resolve().parents[1]
CLUSTERS_DIR = ROOT / 'docs' / 'clusters'


def parse_readme(readme_path: Path, cluster_slug: str):
    """Parse README to extract nodes with registry-compliant attributes."""
    text = readme_path.read_text(encoding='utf-8')
    lines = text.splitlines()
    nodes = []
    seen = set()
    current_type = None

    section_map = {
        'Persons': 'Person',
        'Institutions': 'Institution',
        'Texts/Artifacts': 'Text',
        'Texts': 'Text',
        'Artifacts': 'Text',
        'Movements': 'Movement',
        'Events': 'Event',
        'Places': 'Place'
    }

    # Labels requiring definition vs description per registry
    definition_labels = {'Institution', 'Movement', 'Idea'}
    description_labels = {'Person', 'Place', 'Text', 'Event', 'Artifact', 'Evidence'}

    for i, line in enumerate(lines):
        m = re.match(r'^####\s+([^\n\(]+)', line)
        if m:
            sec = m.group(1).strip()
            if sec in section_map:
                current_type = section_map[sec]
            else:
                for k in section_map:
                    if k.lower() in sec.lower():
                        current_type = section_map[k]
                        break
                else:
                    current_type = None
            continue

        if line.strip().startswith('|') and '---' not in line:
            parts = [p.strip() for p in line.split('|')[1:-1]]
            if not parts:
                continue
            first = parts[0]
            if first.lower() in ('node', ''):
                continue
            if re.match(r'^-+$', first):
                continue
            slug = first
            if not slug:
                continue
            if slug in seen:
                continue
            seen.add(slug)
            
            name = slug.replace('_', ' ').replace('-', ' ')
            label = current_type or 'Concept'
            
            # Build node with registry-compliant attributes
            node = {
                'slug': slug,
                'name': name,
                'label': label,
                'status': 'PROPOSED',
                'workflow_stage': 'PROPOSED',
                'governance_version': 5,
                'created_at': datetime.now(timezone.utc).strftime('%Y-%m-%dT%H:%MZ'),
                'created_by': 'auto:from_readme',
                'lang': 'en',
                'script': 'Latn'
            }
            
            # Add definition or description based on label
            if label in definition_labels:
                node['definition'] = f'{name} ({cluster_slug} cluster node)'
            elif label in description_labels:
                node['description'] = f'{name} from {cluster_slug} cluster'
            else:
                node['description'] = f'{name} node'
            
            nodes.append(node)

    if not nodes:
        for line in lines:
            m = re.match(r'^-\s+([^\|\(].+)$', line)
            if m:
                slug = m.group(1).strip()
                slug = slug.replace(' ', '_')
                if slug in seen:
                    continue
                seen.add(slug)
                name = slug.replace('_', ' ')
                node = {
                    'slug': slug,
                    'name': name,
                    'label': 'Concept',
                    'status': 'PROPOSED',
                    'workflow_stage': 'PROPOSED',
                    'governance_version': 5,
                    'created_at': datetime.now(timezone.utc).strftime('%Y-%m-%dT%H:%MZ'),
                    'created_by': 'auto:from_readme',
                    'lang': 'en',
                    'script': 'Latn',
                    'description': f'{name} from {cluster_slug} cluster'
                }
                nodes.append(node)

    return nodes


def write_nodes(cluster_slug: str, nodes: list, readme_path: Path):
    """Write nodes to cluster-specific JSON with human-readable formatting."""
    tgt = ROOT / 'data' / 'Nodes' / f'nodes.{cluster_slug}.json'
    if tgt.exists():
        bak = tgt.with_suffix('.bak.' + datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%SZ'))
        shutil.copy2(tgt, bak)
        print(f'Backed up {tgt.name} -> {bak.name}')

    out = {
        '_meta': {
            'cluster': cluster_slug,
            'notes': 'Nodes autogenerated from README.md with registry-compliant attributes',
            'registry': 'docs/nodes/node-attribute-registry.md',
            'source': str(readme_path.relative_to(ROOT)),
            'generated_at': datetime.now(timezone.utc).strftime('%Y-%m-%dT%H:%MZ'),
            'generator': 'scripts/generate_nodes_from_readmes.py'
        },
        'nodes': nodes
    }

    tgt.parent.mkdir(parents=True, exist_ok=True)
    with open(tgt, 'w', encoding='utf-8') as f:
        json.dump(out, f, ensure_ascii=False, indent=2)

    print(f'Wrote {tgt.name} with {len(nodes)} nodes')
    if nodes:
        print(f'Sample: {nodes[0]["slug"]} ({nodes[0]["label"]})')


def main():
    """Process all cluster READMEs and generate registry-compliant node JSONs."""
    if not CLUSTERS_DIR.exists():
        print(f'Clusters directory not found: {CLUSTERS_DIR}')
        raise SystemExit(1)

    readmes = sorted((p for p in CLUSTERS_DIR.glob('*/README.md') if p.is_file()))
    if not readmes:
        print(f'No cluster READMEs found under {CLUSTERS_DIR}')
        raise SystemExit(1)

    print(f'Found {len(readmes)} cluster READMEs')
    print('=' * 60)
    
    total_nodes = 0
    processed = 0
    errors = []
    
    for readme in readmes:
        cluster_slug = readme.parent.name
        try:
            print(f'\nProcessing: {cluster_slug}')
            nodes = parse_readme(readme, cluster_slug)
            write_nodes(cluster_slug, nodes, readme)
            total_nodes += len(nodes)
            processed += 1
        except Exception as e:
            error_msg = f'Error processing {cluster_slug}: {e}'
            print(error_msg)
            errors.append(error_msg)

    print('\n' + '=' * 60)
    print('Generation summary:')
    print(f'  Processed clusters: {processed}/{len(readmes)}')
    print(f'  Total nodes generated: {total_nodes}')
    if errors:
        print(f'  Errors during generation: {len(errors)}')
        for err in errors:
            print(f'    - {err}')
    else:
        print(f'  ✓ All clusters generated successfully')


if __name__ == '__main__':
    main()
